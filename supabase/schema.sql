-- Esquema reproducible para un proyecto Supabase nuevo. No contiene usuarios ni contraseñas.
create table if not exists public.productos (
  id bigint generated by default as identity primary key,
  nombre text not null check (char_length(btrim(nombre)) between 3 and 120),
  precio numeric not null check (precio > 0),
  stock integer not null check (stock >= 0),
  created_at timestamptz not null default now()
);

alter table public.productos enable row level security;
grant select, insert, update, delete on public.productos to authenticated;
grant usage, select on sequence public.productos_id_seq to authenticated;
revoke all on public.productos from anon;

drop policy if exists productos_lectura on public.productos;
create policy productos_lectura on public.productos for select to authenticated
using (auth.uid() is not null and coalesce(auth.jwt()->>'is_anonymous','false')='false'
  and auth.jwt()->'app_metadata'->>'rol' in ('admin','usuario'));

drop policy if exists productos_insert_admin on public.productos;
create policy productos_insert_admin on public.productos for insert to authenticated
with check (auth.uid() is not null and coalesce(auth.jwt()->>'is_anonymous','false')='false'
  and auth.jwt()->'app_metadata'->>'rol'='admin');

drop policy if exists productos_update_admin on public.productos;
create policy productos_update_admin on public.productos for update to authenticated
using (auth.uid() is not null and coalesce(auth.jwt()->>'is_anonymous','false')='false'
  and auth.jwt()->'app_metadata'->>'rol'='admin')
with check (auth.uid() is not null and coalesce(auth.jwt()->>'is_anonymous','false')='false'
  and auth.jwt()->'app_metadata'->>'rol'='admin');

drop policy if exists productos_delete_admin on public.productos;
create policy productos_delete_admin on public.productos for delete to authenticated
using (auth.uid() is not null and coalesce(auth.jwt()->>'is_anonymous','false')='false'
  and auth.jwt()->'app_metadata'->>'rol'='admin');

